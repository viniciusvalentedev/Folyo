export type IconName = keyof typeof ICONS

type IconProps = Omit<LucideProps, 'ref'> & {
  /** Nome do ícone. Nomes vindos de dados (ex.: categorias) caem em um círculo se não existirem. */
  name: IconName | (string & {})
  size?: number
}

export function Icon({ name, size = 18, className = '', ...rest }: IconProps) {
  const Component = ICONS[name as IconName] ?? Circle
  return <Component size={size} className={'ico ' + className} aria-hidden="true" strokeWidth={1.75} {...rest} />
}
